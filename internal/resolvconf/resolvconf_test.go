package resolvconf

import (
	"os"
	"path/filepath"
	"slices"
	"testing"
)

func write(t *testing.T, content string) string {
	t.Helper()
	p := filepath.Join(t.TempDir(), "resolv.conf")
	if err := os.WriteFile(p, []byte(content), 0o644); err != nil {
		t.Fatal(err)
	}
	return p
}

func TestNameserversInFileOrder(t *testing.T) {
	p := write(t, "# Generated by NetworkManager\nsearch example.test\nnameserver 192.168.7.1\nnameserver 2001:db8::1 ; secondary\noptions edns0\n")
	got := Nameservers(p)
	want := []string{"192.168.7.1", "2001:db8::1"}
	if !slices.Equal(got, want) {
		t.Errorf("Nameservers = %v, want %v", got, want)
	}
}

func TestNameserversSkipsWhatTheLibraryCannotTake(t *testing.T) {
	p := write(t, "nameserver resolver.example.test\nnameserver fe80::1%eth0\nnameserver\nnameserver 127.0.0.53\n")
	got := Nameservers(p)
	want := []string{"127.0.0.53"}
	if !slices.Equal(got, want) {
		t.Errorf("Nameservers = %v, want %v", got, want)
	}
}

func TestNameserversMissingFileIsNil(t *testing.T) {
	if got := Nameservers(filepath.Join(t.TempDir(), "absent")); got != nil {
		t.Errorf("Nameservers of a missing file = %v, want nil", got)
	}
	if got := Nameservers(write(t, "search example.test\n")); got != nil {
		t.Errorf("Nameservers with no servers = %v, want nil", got)
	}
}
